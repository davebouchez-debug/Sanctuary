# RETRIEVAL FUNCTIONS
# ============================================================

def get_principle_for_context(query: str) -> Optional[Dict]:
    """
    Retrieve the most relevant Interstice principle for the current context.
    """
    query_lower = query.lower()
    
    for key, principle in CORE_PRINCIPLES.items():
        keywords = principle.get("keywords", [])
        for keyword in keywords:
            if keyword in query_lower:
                return {
                    "key": key,
                    "title": principle["title"],
                    "principle": principle["principle"].strip(),
                    "implication": principle["architectural_implication"]
                }
    
    return None


def get_chamber_guidance(chamber_name: str) -> Optional[Dict]:
    """
    Get Interstice-informed guidance for a specific chamber.
    """
    chamber_key = chamber_name.lower().replace(" ", "_")
    return CHAMBER_IMPLICATIONS.get(chamber_key)


def get_drift_recovery(indicator_type: str) -> Optional[Dict]:
    """
    Get recovery guidance for a detected drift pattern.
    """
    return DRIFT_INDICATORS.get(indicator_type)


def get_vocabulary_guidance() -> Dict:
    """
    Return the sacred vocabulary — terms to use and avoid.
    """
    return SACRED_VOCABULARY


def get_all_principles() -> str:
    """
    Return all core principles as a formatted document.
    """
    parts = []
    for key, principle in CORE_PRINCIPLES.items():
        parts.append(f"## {principle['title']}\n\n{principle['principle'].strip()}\n\n**Architectural Implication:** {principle['architectural_implication']}")
    return "\n\n---\n\n".join(parts)


def get_presence_type(presence_name: str) -> Optional[Dict]:
    """
    Get the Interstice typing for a specific presence.
    """
    presence_lower = presence_name.lower()
    for type_key, type_data in PRESENCE_TYPING.items():
        presences_lower = [p.lower() for p in type_data.get("presences", [])]
        if presence_lower in presences_lower:
            return {
                "type": type_key,
                "description": type_data["description"],
                "characteristics": type_data["characteristics"],
                "safeguard": type_data.get("safeguard")
            }
    return None
